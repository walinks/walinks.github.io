#!/usr/bin/env python3
"""Rebuild js/groups-data.js from data/groups.json.

Run from the repo root:  python3 tools/build_data.py
Dedupes invite links inside each list (first name wins) and builds the
derived lists used by the focused landing pages.
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LINK_RE = re.compile(r'^https://(chat\.whatsapp\.com/[A-Za-z0-9]{10,}|www\.whatsapp\.com/channel/[A-Za-z0-9]+)$')

# page key -> (source list, categories to keep; None = all)
DERIVED = {
    "pakistan-jobs":      ("jobs", {"pakistan"}),
    "uae-gulf-jobs":      ("jobs", {"gulf"}),
    "online-earning":     ("jobs", {"online"}),
    "funny-memes":        ("entertainment", {"funny"}),
    "netflix-web-series": ("movies", {"netflix", "web"}),
}

def dedupe(items):
    seen, out = set(), []
    for g in items:
        link = g["link"].split("?")[0].strip()
        if link in seen or not LINK_RE.match(link):
            continue
        seen.add(link)
        out.append({"name": g["name"].strip(), "link": link, "cat": g.get("cat", "all")})
    return out

def main():
    src = json.loads((ROOT / "data/groups.json").read_text(encoding="utf-8"))
    result = {k: dedupe(v) for k, v in src.items()}
    for key, (base, cats) in DERIVED.items():
        result[key] = [g for g in result[base] if g["cat"] in cats]
    js = "/* AUTO-GENERATED by tools/build_data.py from data/groups.json — do not edit by hand. */\n"
    js += "window.WA_GROUPS = " + json.dumps(result, ensure_ascii=False, indent=1) + ";\n"
    (ROOT / "js/groups-data.js").write_text(js, encoding="utf-8")
    print({k: len(v) for k, v in result.items()})

if __name__ == "__main__":
    sys.exit(main())
